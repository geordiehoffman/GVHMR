"""Load npz → SMPL decode → save joints/vertices to JSON"""

import torch
import numpy as np
import json
from smplx import SMPL

# 1. Load .npz
npz_path = '/content/GVHMR/outputs/demo/thatch_factory/hmr4d_results.npz'
data = np.load(npz_path)

global_orient = torch.tensor(data['global_orient'])  # (frames, 3)
body_pose = torch.tensor(data['body_pose'])          # (frames, 63)
betas = torch.tensor(data['betas'])                  # (frames, 10)
transl = torch.tensor(data['transl'])                 # (frames, 3)

# 2. Load SMPL model
smpl = SMPL(
    model_path='/content/GVHMR/inputs/checkpoints/body_models/smpl',
    gender='neutral',
    batch_size=global_orient.shape[0]
)

# 3. Fix body_pose dimension
frames = body_pose.shape[0]
body_pose_padded = torch.cat(
    [body_pose, torch.zeros((frames, 6))],
    dim=1
)

# 4. Forward pass
output = smpl(
    global_orient=global_orient,
    body_pose=body_pose_padded,
    betas=betas,
    transl=transl
)

# 5. Only get joints
joints = output.joints  # (frames, 45, 3)

# 6. Convert to list
joints_list = joints.cpu().numpy().tolist()

# 7. Create dictionary
output_dict = {
    'joints_3d': joints_list
}

# 8. Save to JSON
json_path = npz_path.replace('.npz', '_joints_only.json')
with open(json_path, 'w') as f:
    json.dump(output_dict, f)

print(f"Saved joints ONLY to {json_path}")

