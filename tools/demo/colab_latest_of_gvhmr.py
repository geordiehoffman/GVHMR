import numpy as np
import torch
import matplotlib.pyplot as plt
from mpl_toolkits.mplot3d import Axes3D
from smplx import SMPLX  # you must have smplx installed

# Load GVHMR .npz result
data = np.load('/content/GVHMR/outputs/demo/thatch_factory/hmr4d_results.npz')

frame_idx = 0  # which frame you want

# Extract pose params
global_orient = torch.tensor(data['global_orient'][frame_idx]).unsqueeze(0)  # (1, 3)
body_pose = torch.tensor(data['body_pose'][frame_idx]).unsqueeze(0)          # (1, 63)
betas = torch.tensor(data['betas'][frame_idx]).unsqueeze(0)                  # (1, 10)
transl = torch.tensor(data['transl'][frame_idx]).unsqueeze(0)                # (1, 3)

# Load SMPLX model
model_path = '/content/models/smplx'  # you must download smplx models here
model = SMPLX(model_path=model_path, gender='neutral', use_pca=False)

# Forward model
output = model(global_orient=global_orient, body_pose=body_pose, betas=betas, transl=transl)

vertices = output.vertices[0].detach().cpu().numpy()
joints = output.joints[0].detach().cpu().numpy()

# Plot
fig = plt.figure(figsize=(10, 10))
ax = fig.add_subplot(111, projection='3d')

# Vertices
ax.scatter(vertices[:, 0], vertices[:, 1], vertices[:, 2], s=0.1, c='gray', alpha=0.6, label='Vertices')

# Joints
ax.scatter(joints[:, 0], joints[:, 1], joints[:, 2], s=20, c='red', label='Joints')

ax.set_xlabel('X')
ax.set_ylabel('Y')
ax.set_zlabel('Z')
ax.view_init(elev=20, azim=60)
